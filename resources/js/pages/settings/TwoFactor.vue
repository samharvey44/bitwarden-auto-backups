<script setup>
import { router, useForm, useHttp } from '@inertiajs/vue3';
import { onMounted, ref, watch } from 'vue';
import AppAlert from '../../components/AppAlert.vue';
import AppButton from '../../components/AppButton.vue';
import AppCard from '../../components/AppCard.vue';
import FormField from '../../components/FormField.vue';
import TextInput from '../../components/TextInput.vue';
import SettingsLayout from '../../layouts/SettingsLayout.vue';

const props = defineProps({
    enabled: {
        type: Boolean,
        required: true,
    },
    awaitingConfirmation: {
        type: Boolean,
        required: true,
    },
});

const qrCode = useHttp({});
const secretKey = useHttp({});
const recoveryCodes = useHttp({});
const showRecoveryCodes = ref(false);
const loadError = ref(null);
const processing = ref(false);

const confirmForm = useForm({
    code: '',
});

async function loadSetupDetails() {
    loadError.value = null;

    try {
        await Promise.all([qrCode.get('/user/two-factor-qr-code'), secretKey.get('/user/two-factor-secret-key')]);
    } catch {
        loadError.value = 'The setup QR code could not be loaded. Reload the page to try again.';
    }
}

async function loadRecoveryCodes() {
    loadError.value = null;

    try {
        await recoveryCodes.get('/user/two-factor-recovery-codes');
        showRecoveryCodes.value = true;
    } catch {
        loadError.value = 'Your recovery codes could not be loaded. Reload the page to try again.';
    }
}

function visit(method, url, onSuccess = () => {}) {
    router.visit(url, {
        method,
        preserveScroll: true,
        onStart: () => (processing.value = true),
        onFinish: () => (processing.value = false),
        onSuccess,
    });
}

function enable() {
    visit('post', '/user/two-factor-authentication');
}

function confirm() {
    confirmForm.post('/user/confirmed-two-factor-authentication', {
        errorBag: 'confirmTwoFactorAuthentication',
        preserveScroll: true,
        onSuccess: () => {
            confirmForm.reset();
            loadRecoveryCodes();
        },
    });
}

function regenerateRecoveryCodes() {
    visit('post', '/user/two-factor-recovery-codes', loadRecoveryCodes);
}

function disable() {
    visit('delete', '/user/two-factor-authentication', () => (showRecoveryCodes.value = false));
}

onMounted(() => {
    if (props.awaitingConfirmation) {
        loadSetupDetails();
    }
});

watch(
    () => props.awaitingConfirmation,
    (awaitingConfirmation) => awaitingConfirmation && loadSetupDetails(),
);
</script>

<template>
    <SettingsLayout>
        <AppCard
            title="Two-factor authentication"
            description="Require a code from an authenticator app, as well as your password, when you log in."
        >
            <AppAlert v-if="loadError" tone="error">{{ loadError }}</AppAlert>

            <template v-if="enabled">
                <AppAlert tone="success">Two-factor authentication is on.</AppAlert>

                <div v-if="showRecoveryCodes" class="flex flex-col gap-3">
                    <p class="text-sm text-zinc-600 dark:text-zinc-400">
                        Store these recovery codes somewhere safe. Each one can be used once to log in if you lose access to your authenticator app.
                    </p>
                    <ul class="grid grid-cols-2 gap-2 rounded-md bg-zinc-100 p-4 font-mono text-sm dark:bg-zinc-800">
                        <li v-for="code in recoveryCodes.response" :key="code">{{ code }}</li>
                    </ul>
                </div>

                <div class="flex flex-wrap gap-3">
                    <AppButton v-if="!showRecoveryCodes" variant="secondary" :processing="recoveryCodes.processing" @click="loadRecoveryCodes">
                        Show recovery codes
                    </AppButton>
                    <AppButton v-else variant="secondary" :processing="processing" @click="regenerateRecoveryCodes">Regenerate recovery codes</AppButton>
                    <AppButton variant="danger" :processing="processing" @click="disable">Turn off</AppButton>
                </div>
            </template>

            <template v-else-if="awaitingConfirmation">
                <p class="text-sm text-zinc-600 dark:text-zinc-400">
                    Scan this QR code with your authenticator app, or enter the setup key, then enter the 6-digit code it shows.
                </p>

                <div class="flex flex-col items-start gap-4 sm:flex-row sm:items-center">
                    <!-- The SVG is generated by Fortify on the server, not taken from user input. -->
                    <div v-if="qrCode.response" class="rounded-md bg-white p-3" v-html="qrCode.response.svg" />
                    <div v-if="secretKey.response" class="flex flex-col gap-1 text-sm">
                        <span class="text-zinc-500 dark:text-zinc-400">Setup key</span>
                        <code class="font-mono break-all">{{ secretKey.response.secretKey }}</code>
                    </div>
                </div>

                <form class="flex flex-col gap-5" @submit.prevent="confirm">
                    <FormField label="Authentication code" for="code" :error="confirmForm.errors.code">
                        <TextInput
                            id="code"
                            v-model="confirmForm.code"
                            inputmode="numeric"
                            autocomplete="one-time-code"
                            pattern="[0-9]*"
                            maxlength="6"
                            required
                            :invalid="!!confirmForm.errors.code"
                        />
                    </FormField>

                    <div class="flex flex-wrap gap-3">
                        <AppButton type="submit" :processing="confirmForm.processing">Confirm</AppButton>
                        <AppButton variant="ghost" :processing="processing" @click="disable">Cancel</AppButton>
                    </div>
                </form>
            </template>

            <template v-else>
                <AppAlert tone="warning">
                    Two-factor authentication is off. This app holds your vault credentials, so turning it on is strongly recommended.
                </AppAlert>

                <div>
                    <AppButton :processing="processing" @click="enable">Turn on</AppButton>
                </div>
            </template>
        </AppCard>
    </SettingsLayout>
</template>
